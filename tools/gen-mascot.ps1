# Generates mascot assets from tools/mascot.txt (single source of truth):
#  - app/src/main/java/app/pixelnotebook/ui/MascotSprite.kt
#  - app/src/main/res/drawable/ic_launcher_foreground.xml
#  - tools/mascot_preview.png
# Run: powershell -ExecutionPolicy Bypass -File tools\gen-mascot.ps1
$root = Split-Path $PSScriptRoot -Parent
$rows = Get-Content "$PSScriptRoot\mascot.txt" | Where-Object { $_.Trim() -ne '' }
$pal = [ordered]@{
  'K'='#0B0512'; 'D'='#2A1640'; 'H'='#47296D'; 'L'='#6A43A0'
  'F'='#7B5C9E'; 'S'='#563C78'; 'E'='#B66BFF'; 'W'='#F1E3FF'
  'M'='#D45AAB'; 'Q'='#4A3162'; 'P'='#8A62C0'; 'G'='#5A3E7E'
}
foreach ($r in $rows) { if ($r.Length -ne $rows[0].Length) { throw "Row length mismatch: '$r'" } }
$w = $rows[0].Length; $h = $rows.Count

# Kotlin
$kt = "package app.vesper.ui`n`nimport androidx.compose.ui.graphics.Color`n`n// GENERATED by tools/gen-mascot.ps1 from tools/mascot.txt - do not edit by hand.`nval MascotGrid: List<String> = listOf(`n"
foreach ($r in $rows) { $kt += "    `"$r`",`n" }
$kt += ")`n`nval MascotPalette: Map<Char, Color> = mapOf(`n"
foreach ($k in $pal.Keys) { $kt += "    '$k' to Color(0xFF$($pal[$k].Substring(1))),`n" }
$kt += ")`n"
[IO.File]::WriteAllText("$root\app\src\main\java\app\pixelnotebook\ui\MascotSprite.kt", $kt)

# Vector drawable for adaptive icon (108dp viewport, sprite scaled into safe zone)
$px = 2.6; $ox = (108 - $w*$px)/2; $oy = (108 - $h*$px)/2 + 2
$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine('<vector xmlns:android="http://schemas.android.com/apk/res/android"')
[void]$sb.AppendLine('    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">')
$inv = [Globalization.CultureInfo]::InvariantCulture
for ($y=0; $y -lt $h; $y++) {
  $x = 0
  while ($x -lt $w) {
    $c = $rows[$y][$x]
    if ($c -eq '.') { $x++; continue }
    $x0 = $x
    while ($x -lt $w -and $rows[$y][$x] -eq $c) { $x++ }
    $rx = ($ox + $x0*$px).ToString('0.###',$inv); $ry = ($oy + $y*$px).ToString('0.###',$inv)
    $rw = (($x-$x0)*$px).ToString('0.###',$inv); $rh = $px.ToString('0.###',$inv)
    $col = '#FF' + $pal["$c"].Substring(1)
    [void]$sb.AppendLine("    <path android:fillColor=`"$col`" android:pathData=`"M$rx,${ry}h${rw}v${rh}h-${rw}z`" />")
  }
}
[void]$sb.AppendLine('</vector>')
New-Item -ItemType Directory -Force "$root\app\src\main\res\drawable" | Out-Null
[IO.File]::WriteAllText("$root\app\src\main\res\drawable\ic_launcher_foreground.xml", $sb.ToString())

# Preview PNG
Add-Type -AssemblyName System.Drawing
$s = 16
$bmp = New-Object Drawing.Bitmap ($w*$s), ($h*$s)
$g = [Drawing.Graphics]::FromImage($bmp); $g.Clear([Drawing.ColorTranslator]::FromHtml('#100817'))
for ($y=0; $y -lt $h; $y++) { for ($x=0; $x -lt $w; $x++) {
  $c = $rows[$y][$x]; if ($c -eq '.') { continue }
  $br = New-Object Drawing.SolidBrush ([Drawing.ColorTranslator]::FromHtml($pal["$c"]))
  $g.FillRectangle($br, $x*$s, $y*$s, $s, $s) } }
$bmp.Save("$PSScriptRoot\mascot_preview.png", [Drawing.Imaging.ImageFormat]::Png)
"ok ${w}x${h}"
